import * as z from 'zod/v4';
import {
  definitionOf,
  type AnyFieldDefinitions,
  type Definition,
} from './fields.js';

/** A JSON Schema document, or one of its subschemas, as plain JSON data. */
export interface JSONSchema {
  [keyword: string]: unknown;
}

/**
 * The Edity dialect of JSON Schema 2020-12: the standard vocabularies plus
 * Edity's Limits vocabulary. Its meta-schema is in `contracts/meta/`. Naming
 * it in `$schema` makes a validator that does not know the Limits vocabulary
 * refuse the schema instead of silently ignoring the Limits.
 */
const dialect = 'https://github.com/RMYPG/edity/contracts/v1/schema';

/**
 * The JSON Schema 2020-12 document of a page's Field definitions, which the
 * server validates a Draft against. Limits use the standard keywords where
 * they mean exactly the same thing, and Edity's `x-edity-*` keywords
 * otherwise.
 */
export function toJSONSchema(fields: AnyFieldDefinitions): JSONSchema {
  if (definitionOf(fields)?.kind !== 'object') {
    throw new TypeError(
      "Expected a page's Field definitions, made with defineFields()",
    );
  }
  const schema = z.toJSONSchema(fields, {
    target: 'draft-2020-12',
    // The server validates the content file, which is what Zod parses.
    io: 'input',
    // Only the Field definitions shape the output, not metadata registered
    // elsewhere.
    metadata: z.registry(),
    override: ({ zodSchema, jsonSchema }) => {
      const definition = definitionOf(zodSchema);
      if (definition !== undefined) addLimits(jsonSchema, definition);
    },
  }) as JSONSchema;
  return {
    ...schema,
    $schema: dialect,
    $comment:
      "Generated by Edity from this page's Field definitions. Do not edit.",
  };
}

/**
 * Writes a Field's or a List's Limits into the subschema Zod made for it.
 * Zod's refinements, such as the grapheme count, do not reach JSON Schema, so
 * every Limit is written here, from the definition.
 */
function addLimits(jsonSchema: JSONSchema, definition: Definition): void {
  switch (definition.kind) {
    case 'text': {
      const { maxChars, maxLines, maxLinesNarrow } = definition.limits;
      // Not `maxLength`, which counts code points: an emoji can be several.
      jsonSchema['x-edity-maxGraphemes'] = maxChars;
      if (maxLines !== undefined) jsonSchema['x-edity-maxLines'] = maxLines;
      if (maxLinesNarrow !== undefined) {
        jsonSchema['x-edity-maxLinesNarrow'] = maxLinesNarrow;
      }
      break;
    }
    case 'number': {
      const { min, max, decimals } = definition.limits;
      jsonSchema.minimum = min;
      jsonSchema.maximum = max;
      // Not `multipleOf`, which validators compute differently for floats.
      if (decimals === 0) jsonSchema.type = 'integer';
      else jsonSchema['x-edity-decimals'] = decimals;
      break;
    }
    case 'list':
      jsonSchema.minItems = definition.limits.min;
      jsonSchema.maxItems = definition.limits.max;
      break;
  }
}
