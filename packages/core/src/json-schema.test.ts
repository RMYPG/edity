import { describe, expect, test } from 'vitest';
import * as z from 'zod/v4';
import {
  defineFields,
  list,
  number,
  text,
  toJSONSchema,
  type AnyFieldDefinitions,
  type JSONSchema,
} from '@edity/core';

const dialect = 'https://github.com/RMYPG/edity/contracts/v1/schema';

// What every text Field holds: one line with at least one visible character.
const oneVisibleLine =
  '^[\\t\\v\\f\\p{Zs}]*[^\\t\\v\\f\\p{Zs}\\n\\r\\p{Zl}\\p{Zp}][^\\n\\r\\p{Zl}\\p{Zp}]*$';

describe('toJSONSchema', () => {
  test("describes a page's Field definitions in the Edity dialect of JSON Schema 2020-12", () => {
    const home = defineFields({ title: text({ maxChars: 20 }) });

    expect(toJSONSchema(home)).toEqual({
      $schema: dialect,
      $comment:
        "Generated by Edity from this page's Field definitions. Do not edit.",
      type: 'object',
      properties: {
        title: {
          type: 'string',
          pattern: oneVisibleLine,
          'x-edity-maxGraphemes': 20,
        },
      },
      required: ['title'],
      additionalProperties: false,
    });
  });

  test('keeps the line Limits of a text Field as Edity annotations', () => {
    const home = defineFields({
      title: text({ maxChars: 40, maxLines: 1, maxLinesNarrow: 2 }),
    });

    expect(fieldsOf(home).title).toEqual({
      type: 'string',
      pattern: oneVisibleLine,
      'x-edity-maxGraphemes': 40,
      'x-edity-maxLines': 1,
      'x-edity-maxLinesNarrow': 2,
    });
  });

  test('a number Field keeps its range in the standard keywords and its decimals in an Edity keyword', () => {
    const home = defineFields({
      price: number({ min: 0, max: 999.99, decimals: 2 }),
    });

    // Not `multipleOf: 0.01`: validators disagree on it for floats, so one
    // rejects 19.99 when another accepts it.
    expect(fieldsOf(home).price).toEqual({
      type: 'number',
      minimum: 0,
      maximum: 999.99,
      'x-edity-decimals': 2,
    });
  });

  test('a number Field with no decimals is an integer', () => {
    const home = defineFields({
      sessions: number({ min: 1, max: 20, decimals: 0 }),
    });

    expect(fieldsOf(home).sessions).toEqual({
      type: 'integer',
      minimum: 1,
      maximum: 20,
    });
  });

  test('a List keeps its bounds and its Items, with the Limits of every Field inside', () => {
    const home = defineFields({
      plans: list(
        {
          name: text({ maxChars: 30 }),
          price: number({ min: 0, max: 500, decimals: 2 }),
          features: list(text({ maxChars: 60 }), { min: 0, max: 4 }),
        },
        { min: 1, max: 3 },
      ),
    });

    expect(fieldsOf(home).plans).toEqual({
      type: 'array',
      minItems: 1,
      maxItems: 3,
      items: {
        type: 'object',
        properties: {
          name: {
            type: 'string',
            pattern: oneVisibleLine,
            'x-edity-maxGraphemes': 30,
          },
          price: {
            type: 'number',
            minimum: 0,
            maximum: 500,
            'x-edity-decimals': 2,
          },
          features: {
            type: 'array',
            minItems: 0,
            maxItems: 4,
            items: {
              type: 'string',
              pattern: oneVisibleLine,
              'x-edity-maxGraphemes': 60,
            },
          },
        },
        required: ['name', 'price', 'features'],
        additionalProperties: false,
      },
    });
  });

  test('a group of Fields is an object that accepts only its own Fields', () => {
    const home = defineFields({
      hero: { cta: { label: text({ maxChars: 12 }) } },
    });

    expect(fieldsOf(home).hero).toEqual({
      type: 'object',
      properties: {
        cta: {
          type: 'object',
          properties: {
            label: {
              type: 'string',
              pattern: oneVisibleLine,
              'x-edity-maxGraphemes': 12,
            },
          },
          required: ['label'],
          additionalProperties: false,
        },
      },
      required: ['cta'],
      additionalProperties: false,
    });
  });

  test('a Field used in two places has its Limits in both', () => {
    const label = text({ maxChars: 12, maxLines: 1 });
    const home = defineFields({ hero: { cta: label }, footer: { cta: label } });
    const expected = {
      type: 'string',
      pattern: oneVisibleLine,
      'x-edity-maxGraphemes': 12,
      'x-edity-maxLines': 1,
    };

    expect(fieldsOf(home).hero).toMatchObject({
      properties: { cta: expected },
    });
    expect(fieldsOf(home).footer).toMatchObject({
      properties: { cta: expected },
    });
  });

  test('throws on a schema not made with defineFields()', () => {
    expect(() =>
      // @ts-expect-error: a plain Zod object is not a page's Field definitions.
      toJSONSchema(z.strictObject({ title: z.string() })),
    ).toThrow("Expected a page's Field definitions, made with defineFields()");
  });
});

/** The subschemas of a page's top-level Fields, Lists and groups. */
function fieldsOf(fields: AnyFieldDefinitions): Record<string, JSONSchema> {
  return toJSONSchema(fields).properties as Record<string, JSONSchema>;
}
